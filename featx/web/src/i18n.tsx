function initialLanguage(): Language {
  const saved = localStorage.getItem("featx.language");
  if (saved === "zh" || saved === "en") return saved;
  return "en";
}

export type I18nValues = Record<string, string | number>;

export function interpolate(template: string, values: I18nValues = {}): string {
  return template.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match);
}

type I18nValue = { language: Language; setLanguage: (language: Language) => void;
  t: (text: string, values?: I18nValues) => string };
const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    localStorage.setItem("featx.language", next);
  };
  const value = useMemo(() => ({ language, setLanguage,
    t: (text: string, values?: I18nValues) => interpolate(language === "zh" ? (M[text] ?? text) : text, values) }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used below I18nProvider");
  return value;
}

export function LanguageToggle() {
  const { language, setLanguage, t } = useI18n();
  return (
    <span className="language-toggle" role="group" aria-label={t("language")}>
      <button className={`link ${language === "en" ? "active" : ""}`} onClick={() => setLanguage("en")}>EN</button>
      <span className="muted">/</span>
      <button className={`link ${language === "zh" ? "active" : ""}`} onClick={() => setLanguage("zh")}>中文</button>
    </span>
  );
}
